// Writes the Arch Linux (AUR) package "point-tracker-bin" for the current version:
// packaging/aur/PKGBUILD and packaging/aur/.SRCINFO. The package installs the .deb files from
// the GitHub release, so run this after the release is published:
//   node scripts/aur.mjs
// Then copy both files into the AUR git repo (ssh://aur@aur.archlinux.org/point-tracker-bin.git) and push.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const REPO = "https://github.com/TrueCRaysball/point-tracker";
const version = JSON.parse(readFileSync("src-tauri/tauri.conf.json", "utf8")).version;
const pkgrel = process.argv[2] ?? "1"; // bump only when repackaging the same version
const debs = {
  x86_64: `Point.Tracker_${version}_amd64.deb`,
  aarch64: `Point.Tracker_${version}_arm64.deb`,
};

const sums = {};
for (const [arch, file] of Object.entries(debs)) {
  const url = `${REPO}/releases/download/v${version}/${file}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Couldn't download ${url} (${res.status}). Is v${version} published?`);
  sums[arch] = createHash("sha256").update(Buffer.from(await res.arrayBuffer())).digest("hex");
  console.log(`${arch}: ${file} ${sums[arch]}`);
}

const desc = "Track attendance points, reprimands and medical leave";
const depends = ["webkit2gtk-4.1", "gtk3"];

const pkgbuild = `# Maintainer: CRaysball Softworks
# Generated by scripts/aur.mjs in ${REPO}. Edit that script, not this file.
pkgname=point-tracker-bin
pkgver=${version}
pkgrel=${pkgrel}
pkgdesc="${desc}"
arch=('x86_64' 'aarch64')
url="${REPO}"
license=('LicenseRef-CRaysball-Softworks')
depends=(${depends.map((d) => `'${d}'`).join(" ")})
provides=('point-tracker')
conflicts=('point-tracker')
options=('!strip' '!debug')
source_x86_64=("point-tracker-\${pkgver}-x86_64.deb::\${url}/releases/download/v\${pkgver}/${debs.x86_64.replace(version, "${pkgver}")}")
source_aarch64=("point-tracker-\${pkgver}-aarch64.deb::\${url}/releases/download/v\${pkgver}/${debs.aarch64.replace(version, "${pkgver}")}")
sha256sums_x86_64=('${sums.x86_64}')
sha256sums_aarch64=('${sums.aarch64}')

package() {
  # makepkg unpacks the .deb; the app's files are in data.tar.*
  bsdtar -xf data.tar.* -C "\${pkgdir}"
  # The .deb names its menu entry "Point Tracker.desktop"; use the usual lowercase name.
  mv "\${pkgdir}/usr/share/applications/Point Tracker.desktop" "\${pkgdir}/usr/share/applications/point-tracker.desktop"
  install -dm755 "\${pkgdir}/usr/share/licenses/\${pkgname}"
  echo "Copyright © 2026 CRaysball Softworks. All rights reserved." > "\${pkgdir}/usr/share/licenses/\${pkgname}/LICENSE"
}
`;

// Same content makepkg --printsrcinfo would produce (the AUR requires it next to the PKGBUILD).
const srcinfo = `pkgbase = point-tracker-bin
\tpkgdesc = ${desc}
\tpkgver = ${version}
\tpkgrel = ${pkgrel}
\turl = ${REPO}
\tarch = x86_64
\tarch = aarch64
\tlicense = LicenseRef-CRaysball-Softworks
${depends.map((d) => `\tdepends = ${d}`).join("\n")}
\tprovides = point-tracker
\tconflicts = point-tracker
\toptions = !strip
\toptions = !debug
\tsource_x86_64 = point-tracker-${version}-x86_64.deb::${REPO}/releases/download/v${version}/${debs.x86_64}
\tsha256sums_x86_64 = ${sums.x86_64}
\tsource_aarch64 = point-tracker-${version}-aarch64.deb::${REPO}/releases/download/v${version}/${debs.aarch64}
\tsha256sums_aarch64 = ${sums.aarch64}

pkgname = point-tracker-bin
`;

mkdirSync("packaging/aur", { recursive: true });
writeFileSync("packaging/aur/PKGBUILD", pkgbuild);
writeFileSync("packaging/aur/.SRCINFO", srcinfo);
console.log(`Wrote packaging/aur/PKGBUILD and .SRCINFO for point-tracker-bin ${version}-${pkgrel}.`);
